function inPoly(lon: number, lat: number, poly: [number, number][]) {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

/** 经纬度 → 单位球坐标（y 向北，x 指向经度 0，从外部看东经向右） */
export function lonLatToXyz(lon: number, lat: number): [number, number, number] {
  const la = (lat * Math.PI) / 180, lo = (lon * Math.PI) / 180;
  return [Math.cos(la) * Math.cos(lo), Math.sin(la), -Math.cos(la) * Math.sin(lo)];
}

let cache: Float32Array | null = null;

/** Fibonacci 球面采样后只留陆地点，返回 [x,y,z, x,y,z, …] */
export function landDots(samples = 16000): Float32Array {
  if (cache) return cache;
  const out: number[] = [];
  const ga = Math.PI * (3 - Math.sqrt(5));
  const boxes = LAND.map(p => {
    let a = Infinity, b = -Infinity, c = Infinity, d = -Infinity;
    for (const [x, y] of p) { a = Math.min(a, x); b = Math.max(b, x); c = Math.min(c, y); d = Math.max(d, y); }
    return [a, b, c, d];
  });
  for (let i = 0; i < samples; i++) {
    const y = 1 - (i / (samples - 1)) * 2;
    const r = Math.sqrt(1 - y * y);
    const th = ga * i;
    const x = Math.cos(th) * r, z = Math.sin(th) * r;
    const lat = (Math.asin(y) * 180) / Math.PI;
    const lon = (Math.atan2(-z, x) * 180) / Math.PI;
    let land = false;
    for (let k = 0; k < LAND.length && !land; k++) {
      const bb = boxes[k];
      if (lon < bb[0] || lon > bb[1] || lat < bb[2] || lat > bb[3]) continue;
      land = inPoly(lon, lat, LAND[k]);
    }
    if (land) out.push(x, y, z);
  }
  cache = new Float32Array(out);
  return cache;
}
